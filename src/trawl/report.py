"""Markdown for notes, HTML for the thing you actually open."""

import html
from datetime import UTC, datetime
from pathlib import Path

from trawl import __version__
from trawl.models import NOTHING, Finding, Host, Port, ScanReport, WebHit

_SEV_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}


def write_reports(
    directory: Path,
    report: ScanReport,
    *,
    when: str | None = None,
) -> tuple[Path, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    stamp = when or datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")
    markdown_path = directory / "report.md"
    html_path = directory / "report.html"
    markdown_path.write_text(
        render_markdown(report, when=stamp, version=__version__),
        encoding="utf-8",
    )
    html_path.write_text(
        render_html(report, when=stamp, version=__version__),
        encoding="utf-8",
    )
    return markdown_path, html_path


def render_markdown(report: ScanReport, *, when: str, version: str) -> str:
    lines: list[str] = [
        "# trawl report",
        "",
        f"- generated: {md(when)}",
        f"- targets: {', '.join(md_code(t) for t in report.targets) or 'none'}",
        f"- {_summary(report)}",
        "",
    ]
    for line in quiet_lines(report):
        lines.append(f"> {md(line)}")
        lines.append("")

    if report.notes:
        lines.append("## Notes")
        lines.append("")
        for note in report.notes:
            lines.append(f"- {md(note)}")
        lines.append("")

    if report.skipped:
        lines.append("## Skipped")
        lines.append("")
        for item in report.skipped:
            lines.append(f"- {md(item.tool)}: {md(item.reason)}")
        lines.append("")

    if report.hosts:
        lines.append("## Hosts")
        lines.append("")
        for host in report.hosts:
            lines.extend(_host_markdown(host))

    if report.web:
        lines.append("## Web")
        lines.append("")
        lines.append("| status | length | words | url |")
        lines.append("| --- | --- | --- | --- |")
        for hit in _sorted_web(report):
            lines.append(f"| {hit.status} | {hit.length} | {hit.words} | {md_code(hit.url)} |")
        lines.append("")

    if report.findings:
        lines.append("## Templates")
        lines.append("")
        for finding in _sorted_findings(report):
            lines.extend(_finding_markdown(finding))

    lines.append("---")
    lines.append("")
    lines.append(f"Generated by trawl {md(version)}. Authorised targets only.")
    lines.append("")
    lines.append("<!-- tight lines -->")
    lines.append("")
    return "\n".join(lines)


def render_html(report: ScanReport, *, when: str, version: str) -> str:
    parts = [
        "<!DOCTYPE html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8"/>',
        '<meta name="viewport" content="width=device-width, initial-scale=1"/>',
        f"<title>trawl report · {esc(when)}</title>",
        f"<style>{_CSS}</style>",
        "</head>",
        "<body>",
        "<main>",
        "<header>",
        "<h1>trawl report</h1>",
        f"<p>{esc(_summary(report))}</p>",
        '<ul class="meta">',
        f"<li>generated {esc(when)}</li>",
        f"<li>trawl {esc(version)}</li>",
        "</ul>",
        '<ul class="meta targets">',
    ]
    for target in report.targets:
        parts.append(f"<li>{esc(target)}</li>")
    if not report.targets:
        parts.append("<li>no targets</li>")
    parts.append("</ul>")
    parts.append("</header>")

    for line in quiet_lines(report):
        parts.append(f'<p class="empty">{esc(line)}</p>')

    if report.notes:
        parts.append("<h2>Notes</h2><ul>")
        for note in report.notes:
            parts.append(f"<li>{esc(note)}</li>")
        parts.append("</ul>")

    if report.skipped:
        parts.append("<h2>Skipped</h2><ul>")
        for item in report.skipped:
            parts.append(f"<li><strong>{esc(item.tool)}</strong> {esc(item.reason)}</li>")
        parts.append("</ul>")

    if report.hosts:
        parts.append("<h2>Hosts</h2>")
        for host in report.hosts:
            parts.append(_host_html(host))

    if report.web:
        parts.append("<h2>Web</h2>")
        parts.append(
            "<table><thead><tr><th>status</th><th>length</th><th>words</th><th>url</th></tr></thead><tbody>"
        )
        for hit in _sorted_web(report):
            parts.append(
                "<tr>"
                f"<td>{hit.status}</td>"
                f"<td>{hit.length}</td>"
                f"<td>{hit.words}</td>"
                f"<td>{_link(hit.url)}</td>"
                "</tr>"
            )
        parts.append("</tbody></table>")

    if report.findings:
        parts.append("<h2>Templates</h2>")
        for finding in _sorted_findings(report):
            parts.append(_finding_html(finding))

    parts.append(f"<footer>Generated by trawl {esc(version)}. Authorised targets only.</footer>")
    parts.append("</main>")
    parts.append("<!-- tight lines -->")
    parts.append("</body></html>")
    parts.append("")
    return "\n".join(parts)


def quiet_lines(report: ScanReport) -> list[str]:
    if report.nothing_caught():
        return [NOTHING]
    lines: list[str] = []
    for tool in ("nmap", "ffuf", "nuclei"):
        if tool in report.counts and report.counts[tool] == 0:
            lines.append(f"{tool}: {NOTHING}")
    return lines


def _summary(report: ScanReport) -> str:
    return " · ".join(
        [
            _n(len(report.open_ports()), "open port", "open ports"),
            _n(len(report.web), "path", "paths"),
            _n(len(report.findings), "template match", "template matches"),
        ]
    )


def _n(count: int, singular: str, plural: str) -> str:
    return f"{count} {singular if count == 1 else plural}"


def _host_markdown(host: Host) -> list[str]:
    lines = [f"### {md(host.label)}", ""]
    if host.label != host.address and host.address:
        lines.append(f"{md_code(host.address)} · {md(host.status)}")
    else:
        lines.append(md(host.status))
    lines.append("")
    open_ports = [port for port in host.ports if port.is_open]
    if not open_ports:
        lines.append("No open ports.")
        lines.append("")
        return lines
    lines.append("| port | proto | service | version |")
    lines.append("| --- | --- | --- | --- |")
    for port in open_ports:
        cells = " | ".join(
            [
                str(port.port),
                md(port.protocol),
                md(port.service_label),
                md(port.version_label),
            ]
        )
        lines.append(f"| {cells} |")
    lines.append("")
    scripts = _script_lines(open_ports)
    if scripts:
        for script in scripts:
            lines.append(f"- {md(script)}")
        lines.append("")
    return lines


def _finding_markdown(finding: Finding) -> list[str]:
    title = finding.name or finding.template_id or "untitled"
    lines = [f"### {md(finding.severity)} · {md(title)}", ""]
    if finding.template_id:
        lines.append(f"- template: {md_code(finding.template_id)}")
    if finding.host:
        lines.append(f"- host: {md_code(finding.host)}")
    if finding.matched_at:
        lines.append(f"- matched: {md_code(finding.matched_at)}")
    if finding.tags:
        lines.append(f"- tags: {md(', '.join(finding.tags))}")
    if finding.description:
        lines.append("")
        lines.append(md(finding.description))
    lines.append("")
    return lines


def _host_html(host: Host) -> str:
    bits = ['<section class="host">', f"<h3>{esc(host.label)}</h3>"]
    if host.label != host.address and host.address:
        bits.append(f'<p class="muted">{esc(host.address)} · {esc(host.status)}</p>')
    else:
        bits.append(f'<p class="muted">{esc(host.status)}</p>')
    open_ports = [port for port in host.ports if port.is_open]
    if not open_ports:
        bits.append("<p>No open ports.</p></section>")
        return "".join(bits)
    bits.append(
        "<table><thead><tr><th>port</th><th>proto</th><th>service</th><th>version</th></tr></thead><tbody>"
    )
    for port in open_ports:
        bits.append(
            "<tr>"
            f"<td>{port.port}</td>"
            f"<td>{esc(port.protocol)}</td>"
            f"<td>{esc(port.service_label)}</td>"
            f"<td>{esc(port.version_label)}</td>"
            "</tr>"
        )
    bits.append("</tbody></table>")
    scripts = _script_lines(open_ports)
    if scripts:
        bits.append('<ul class="scripts">')
        for script in scripts:
            bits.append(f"<li>{esc(script)}</li>")
        bits.append("</ul>")
    bits.append("</section>")
    return "".join(bits)


def _finding_html(finding: Finding) -> str:
    title = finding.name or finding.template_id or "untitled"
    sev = finding.severity if finding.severity in _SEV_ORDER else "unknown"
    bits = [
        '<article class="finding">',
        "<h3>",
        f'<span class="sev {sev}">{esc(finding.severity or "unknown")}</span> ',
        esc(title),
        "</h3>",
    ]
    meta: list[str] = []
    if finding.template_id:
        meta.append(esc(finding.template_id))
    if finding.tags:
        meta.append(esc(", ".join(finding.tags)))
    if meta:
        bits.append(f'<p class="muted">{" · ".join(meta)}</p>')
    if finding.matched_at:
        bits.append(f"<p>matched {_link(finding.matched_at)}</p>")
    elif finding.host:
        bits.append(f"<p>host {_link(finding.host)}</p>")
    if finding.description:
        bits.append("<details><summary>description</summary>")
        bits.append(f"<p>{esc(finding.description)}</p></details>")
    bits.append("</article>")
    return "".join(bits)


def _script_lines(ports: list[Port]) -> list[str]:
    lines: list[str] = []
    for port in ports:
        for sid, output in port.scripts:
            lines.append(f"{port.port}/{port.protocol} {sid}: {output}")
    return lines


def _sorted_web(report: ScanReport) -> list[WebHit]:
    return sorted(report.web, key=lambda hit: (hit.status, hit.url))


def _sorted_findings(report: ScanReport) -> list[Finding]:
    return sorted(
        report.findings,
        key=lambda item: (_SEV_ORDER.get(item.severity, 9), item.name, item.matched_at),
    )


def _link(url: str) -> str:
    safe = esc(url)
    if url.startswith(("http://", "https://")):
        return f'<a href="{safe}" rel="noreferrer">{safe}</a>'
    return safe


def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def md(value: object) -> str:
    raw = " ".join(str(value).split())
    return raw.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("|", "\\|")


def md_code(value: object) -> str:
    cleaned = md(value).replace("`", "'")
    return f"`{cleaned}`"


